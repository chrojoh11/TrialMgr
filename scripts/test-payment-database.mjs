// Isolated PostgreSQL validation; never connects to Supabase.
// node scripts/test-payment-database.mjs <path-to-pglite/dist/index.js>
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { PGlite } = await import(pathToFileURL(resolve(process.argv[2])).href);
const db = new PGlite();
const trial = '00000000-0000-0000-0000-000000000001';
const entry = '00000000-0000-0000-0000-000000000002';
await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql as $$select '${trial}'::uuid$$;
create table sdda_trials(id uuid primary key,status text,scent_component_fee_cents integer,scent_three_component_fee_cents integer,elite_fee_cents integer);
create table sdda_dogs(id uuid primary key,call_name text);
create table sdda_entries(id uuid primary key,trial_id uuid,dog_id uuid,confirmation_status text,handler_name text);
create table sdda_runs(entry_id uuid,trial_day_id uuid,level text);
create table sdda_game_offerings(id uuid primary key,entry_fee_cents integer,feo_fee_cents integer);
create table sdda_game_runs(entry_id uuid,offering_id uuid,entry_type text);
create table sdda_financial_transactions(id uuid primary key default gen_random_uuid(),trial_id uuid,entry_id uuid,transaction_type text,amount_cents integer,payment_method text,reference text,notes text,occurred_on date,created_by uuid);
create table sdda_audit_records(trial_id uuid,actor_id uuid,action text,entity_type text,entity_id text,before_state jsonb,after_state jsonb);
create function sdda_can_manage_finances(uuid) returns boolean language sql as $$select coalesce(current_setting('test.allowed',true),'yes') <> 'no'$$;
alter table sdda_financial_transactions enable row level security;
grant all on sdda_financial_transactions to authenticated;
create policy sdda_financial_write on sdda_financial_transactions for all to authenticated using(true) with check(true);
insert into sdda_trials values('${trial}','open',3000,8000,10000);
insert into sdda_entries values('${entry}','${trial}',null,'accepted','Test Handler');
insert into sdda_runs values('${entry}','${trial}','Started'),('${entry}','${trial}','Started'),('${entry}','${trial}','Started');
`);
await db.exec(await readFile(new URL('../supabase/sdda-migrations/20260902_0043_payment_workflow.sql', import.meta.url), 'utf8'));
const scalar = async (sql, args=[]) => Object.values((await db.query(sql,args)).rows[0])[0];
const save = (type,amount,id=null,reverses=null) => scalar('select sdda_save_financial_transaction_v2($1,$2,$3,$4,null,null,$5,current_date,$6,null,$7)',[trial,entry,type,amount,'Test reason',id,reverses]);
assert.equal(Number(await scalar('select sdda_entry_charge_cents($1)',[entry])),8000);
const payment = await save('payment',3000);
await assert.rejects(save('refund',3001),/Refund cannot exceed/);
await assert.rejects(save('waiver',5001),/Waiver cannot exceed/);
const waiver = await save('waiver',5000);
await assert.rejects(save('waiver',1),/Waiver cannot exceed/);
await save('waiver_restore',5000,null,waiver);
await assert.rejects(save('waiver_restore',5000,null,waiver),/already been restored/);
await assert.rejects(scalar('select sdda_delete_financial_transaction($1)',[waiver]),/waiver history/);
await save('refund',1000);
await assert.rejects(save('payment',999,payment),/Refund cannot exceed/);
await assert.rejects(scalar('select sdda_delete_financial_transaction($1)',[payment]),/Correct the refunds/);
await save('adjustment',-500);
await assert.rejects(save('entry_fee',100),/Entry fees are automatic/);
const count = await scalar('select count(*) from sdda_financial_transactions');
await assert.rejects(scalar('select sdda_record_payment_batch($1,$2,null,null,null,current_date)',[trial,JSON.stringify([{entryId:entry,amountCents:100},{entryId:trial,amountCents:100}])]),/Choose an entry/);
assert.equal(await scalar('select count(*) from sdda_financial_transactions'),count,'failed batch rolls back entirely');
await db.exec("set test.allowed='no'");
await assert.rejects(save('payment',100),/Financial access required/);
await db.exec("set test.allowed='yes'; set role authenticated");
await assert.rejects(db.exec(`insert into sdda_financial_transactions(trial_id,transaction_type,amount_cents) values('${trial}','payment',100)`),/row-level security/);
await db.exec('reset role');
await db.exec("update sdda_trials set status='completed'");
await assert.rejects(save('payment',100),/Reopen this trial/);
await assert.rejects(scalar('select sdda_delete_financial_transaction($1)',[payment]),/Reopen this trial/);
await db.close();
console.log('Payment migration executed successfully; pricing, waiver restoration, refund/edit limits, atomic rollback, permissions and RLS checks passed.');
